// Generate ESM ports of the pinned React CJS builds (`src/vendor/*.js`).
//
// Why: `react`, `react-reconciler` and `scheduler` ship CommonJS only, and the Rendrix
// build pipeline (`packages/cli/src/app/build.mjs`) bundles ES modules — a bare `require`
// or `module.exports` has no host in the runtime. The adapter therefore vendors ESM ports of
// the three pinned `cjs/*.production.js` builds. The transform is mechanical and asserted
// below (exact versions, no `process.env`, no stray `require(`), so regenerating from the
// pinned `node_modules` copies always yields the same output:
//
//   node scripts/vendor.mjs            # regenerate (also runs via `npm test` / pretest)
//
// `ensureVendor()` (used by the tests) regenerates only when `src/vendor/versions.json`
// disagrees with the pins. Nothing here touches the engine.

import { mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const PINS = {
  react: '19.3.1',
  'react-reconciler': '0.34.0',
  scheduler: '0.28.0',
};

const here = path.dirname(fileURLToPath(import.meta.url));
const adapterRoot = path.resolve(here, '..');
const vendorDir = path.join(adapterRoot, 'src', 'vendor');

const CJS_FILE = {
  react: 'cjs/react.production.js',
  scheduler: 'cjs/scheduler.production.js',
  'react-reconciler': 'cjs/react-reconciler.production.js',
  'react-reconciler-constants': 'cjs/react-reconciler-constants.production.js',
};

async function findPackageRoot(pkg) {
  let dir = adapterRoot;
  for (;;) {
    try {
      if ((await stat(path.join(dir, 'node_modules', pkg))).isDirectory()) {
        return path.join(dir, 'node_modules', pkg);
      }
    } catch { /* keep walking up */ }
    const up = path.dirname(dir);
    if (up === dir) return null;
    dir = up;
  }
}

async function loadCjs(pkg, version) {
  const root = await findPackageRoot(pkg);
  if (!root) throw new Error(`vendor: cannot find package '${pkg}' in node_modules (run install first)`);
  const installed = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8')).version;
  if (installed !== version) {
    throw new Error(`vendor: ${pkg}@${installed} installed, but package.json pins ${version} — install the pinned version`);
  }
  return readFile(path.join(root, CJS_FILE[pkg]), 'utf8');
}

/** Names assigned as `exports.NAME = ...` at the top level of a CJS build. */
function exportNames(source) {
  const names = new Set();
  for (const m of source.matchAll(/^exports\.([A-Za-z_$][\w$]*) *=/gm)) names.add(m[1]);
  return [...names].sort();
}

function header(pkg, version, file) {
  return (
    `// GENERATED by scripts/vendor.mjs — do not edit by hand.\n` +
    `// ESM port of ${pkg}@${version} ${file} (production build).\n` +
    `// The upstream file is CommonJS-only; this port declares the free \`exports\`\n` +
    `// object as a module-local const and re-exports it, so the Rendrix ESM-only\n` +
    `// bundler accepts it. Regenerate with \`node scripts/vendor.mjs\`.\n`
  );
}

function esmLeaf(pkg, version, source) {
  if (/process\s*\.\s*env/.test(source)) throw new Error(`vendor: ${pkg} references process.env`);
  if (/\brequire\s*\(/.test(source)) throw new Error(`vendor: ${pkg} contains require()`);
  const names = exportNames(source);
  if (!names.length) throw new Error(`vendor: ${pkg} has no exports.* assignments`);
  // The build declares its own top-level bindings (e.g. `Children`), so it runs inside
  // a function scope parameterized over `exports`; only the footer lives at module scope.
  const lines = names.map(n => `export const ${n} = exports.${n};`);
  return (
    header(pkg, version, CJS_FILE[pkg]) +
    `const exports = {};\n` +
    `(function (exports) {\n` +
    source +
    (source.endsWith('\n') ? '' : '\n') +
    `})(exports);\n` +
    lines.join('\n') +
    `\nexport default exports;\n`
  );
}

function esmReconciler(version, source) {
  if (/process\s*\.\s*env/.test(source)) throw new Error('vendor: react-reconciler references process.env');
  const requires = [...source.matchAll(/\brequire\s*\(\s*(['"])(.*?)\1\s*\)/g)].map(m => m[2]).sort();
  if (requires.join(',') !== 'react,scheduler') {
    throw new Error(`vendor: unexpected requires in react-reconciler: ${requires.join(',')}`);
  }
  const tail = `module.exports.default = module.exports;\nObject.defineProperty(module.exports, "__esModule", { value: !0 });`;
  if (!source.includes('module.exports = function ($$$config)')) {
    throw new Error('vendor: react-reconciler factory entry not found');
  }
  if (!source.trimEnd().endsWith(tail)) throw new Error('vendor: react-reconciler tail changed');
  const body = source
    .split('require("react")').join('__rendrix_react')
    .split("require('react')").join('__rendrix_react')
    .split('require("scheduler")').join('__rendrix_scheduler')
    .split("require('scheduler')").join('__rendrix_scheduler');
  if (/\brequire\s*\(/.test(body)) throw new Error('vendor: leftover require() in react-reconciler');
  const core = body.slice(0, body.trimEnd().length - tail.length).replace(/^"use strict";\s*\n/, '');
  return (
    header('react-reconciler', version, CJS_FILE['react-reconciler']) +
    `import __rendrix_react from './react.js';\n` +
    `import __rendrix_scheduler from './scheduler.js';\n` +
    `const module = { exports: {} };\n` +
    core +
    (core.endsWith('\n') ? '' : '\n') +
    `const __reconcilerFactory = module.exports;\n` +
    `export default __reconcilerFactory;\n`
  );
}

export async function generateVendor() {
  const [reactSrc, schedulerSrc, reconcilerSrc, constantsSrc] = await Promise.all([
    loadCjs('react', PINS.react),
    loadCjs('scheduler', PINS.scheduler),
    loadCjs('react-reconciler', PINS['react-reconciler']),
    (async () => {
      const root = await findPackageRoot('react-reconciler');
      if (!root) throw new Error("vendor: cannot find package 'react-reconciler' in node_modules");
      return readFile(path.join(root, CJS_FILE['react-reconciler-constants']), 'utf8');
    })(),
  ]);
  await mkdir(vendorDir, { recursive: true });
  await Promise.all([
    writeFile(path.join(vendorDir, 'react.js'), esmLeaf('react', PINS.react, reactSrc)),
    writeFile(path.join(vendorDir, 'scheduler.js'), esmLeaf('scheduler', PINS.scheduler, schedulerSrc)),
    writeFile(path.join(vendorDir, 'reconciler.js'), esmReconciler(PINS['react-reconciler'], reconcilerSrc)),
    writeFile(path.join(vendorDir, 'constants.js'), esmLeaf('react-reconciler', PINS['react-reconciler'], constantsSrc)),
    writeFile(path.join(vendorDir, 'versions.json'), JSON.stringify({ ...PINS, generated: 'scripts/vendor.mjs' }, null, 2) + '\n'),
  ]);
  return vendorDir;
}

/** Regenerate the vendor ports only when pins/versions disagree with what's on disk. */
export async function ensureVendor() {
  try {
    const raw = JSON.parse(await readFile(path.join(vendorDir, 'versions.json'), 'utf8'));
    const fresh =
      raw.react === PINS.react &&
      raw.scheduler === PINS.scheduler &&
      raw['react-reconciler'] === PINS['react-reconciler'] &&
      (await Promise.all(['react.js', 'scheduler.js', 'reconciler.js', 'constants.js'].map(f => stat(path.join(vendorDir, f)).then(() => true, () => false)))).every(Boolean);
    if (fresh) return 'fresh';
  } catch { /* fall through to generate */ }
  await generateVendor();
  return 'generated';
}

/** True when the three pinned packages resolve (used to skip headless tests offline). */
export function haveReact() {
  try {
    for (const pkg of Object.keys(PINS)) {
      // Second arg (parent URL) is honored on recent Node; fall back to a manual probe below.
      import.meta.resolve(pkg, path.join(adapterRoot, 'src', 'index.js'));
    }
    return true;
  } catch {
    return false;
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await generateVendor();
  console.log(`vendored react@${PINS.react} react-reconciler@${PINS['react-reconciler']} scheduler@${PINS.scheduler} → src/vendor/`);
}
